// Writes savedmap/static/icons.js: only the Lucide icons the app uses (found as "kebab-name" strings
// in index.html and app.js), instead of shipping the whole 480 KB library.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

globalThis.window = globalThis; globalThis.self = globalThis;
const lucide = createRequire(import.meta.url)("./lucide-1.70.0.min.js");
const icons = (lucide.icons ? lucide : globalThis.lucide).icons;
const src = ["index.html", "app.js"].map(f => readFileSync(new URL(`../savedmap/static/${f}`, import.meta.url), "utf8")).join("\n");
const pascal = n => n.split("-").map(w => w[0].toUpperCase() + w.slice(1)).join("");
const used = {};
for (const [, name] of src.matchAll(/["'`]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)["'`]/g)) {
  const key = pascal(name);
  if (icons[key]) used[key] = icons[key];
}
writeFileSync(new URL("../savedmap/static/icons.js", import.meta.url),
  `// Generated by scripts/build_icons.mjs from Lucide 1.70.0 (ISC). Do not edit.\nwindow.ICONS = ${JSON.stringify(used)};\n`);
console.log(`icons.js: ${Object.keys(used).length} icons`);
